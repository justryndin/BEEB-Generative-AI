def game_weekday(ts: int) -> int:
    """0 = понедельник по серверному (UTC) времени."""
    return (ts // DAY + 3) % 7


@dataclass
class Today:
    weekday: int
    day: Day | None
    tomorrow: Day | None
    ends_at: int  # конец игрового дня (UTC)

    def windows(self):
        """(что, МСК с, МСК до, UTC с, UTC до)."""
        if not self.day:
            return []
        return [(w, a, b, (a - MSK_OFFSET) % 24, (b - MSK_OFFSET) % 24) for w, a, b in self.day.windows]


def today(ts: int) -> Today:
    wd = game_weekday(ts)
    return Today(wd, DAYS.get(wd), DAYS.get((wd + 1) % 7), (ts // DAY + 1) * DAY)
