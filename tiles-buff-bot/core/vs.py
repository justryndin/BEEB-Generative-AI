def game_weekday(ts: int) -> int:
    """0 = понедельник по серверному (UTC) времени."""
    return (ts // DAY + 3) % 7


@dataclass
class Today:
    weekday: int
    day: Day | None
    tomorrow: Day | None
    ends_at: int  # конец игрового дня (UTC)
    ts: int = 0

    def windows(self) -> list[powerplay.Slot]:
        """Окна «Игры по-крупному», где тема совпадает с сегодняшней Дуэлью."""
        return powerplay.duel_windows(self.ts) if self.day else []

    def power_play(self) -> tuple[powerplay.Slot, powerplay.Slot]:
        """Какая тема «Игры по-крупному» идёт сейчас и какая следующая."""
        return powerplay.now_and_next(self.ts)


def today(ts: int) -> Today:
    wd = game_weekday(ts)
    return Today(wd, DAYS.get(wd), DAYS.get((wd + 1) % 7), (ts // DAY + 1) * DAY, ts)
