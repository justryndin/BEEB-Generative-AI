BY_SLUG = {x.slug: x for x in FAQ}


def top(n: int) -> list[QA]:
    """Самые частые — для главной."""
    order = ("water", "vs-today", "whom", "reset", "alts", "pp30")
    return [BY_SLUG[s] for s in order][:n]


@dataclass
class Hit:
    kind: str  # faq, guide, tip
    title: str
    snippet: str
    url: str
    score: int


_TAG = re.compile(r"<[^>]+>")


def _words(text: str) -> list[str]:
    return [w for w in re.findall(r"\w+", text.lower()) if len(w) > 1]


def _score(query: list[str], text: str) -> int:
    t = text.lower()
    return sum(3 if f" {w}" in f" {t}" else 1 for w in query if w in t) if query else 0


def search(q: str, translate=lambda s: s, guides=(), tips=()) -> list[Hit]:
    """Поиск по вопросам, гайдам и советам на языке игрока (translate — перевод русского ключа)."""
    words = _words(q)
    if not words:
        return []
    hits = []
    for x in FAQ:
        title, body = translate(x.q), _TAG.sub("", translate(x.a))
        s = _score(words, title) * 2 + _score(words, body)
        if s:
            hits.append(Hit("faq", title, body[:180], f"/faq#{x.slug}", s + 2))
    for g in guides:
        title, body = translate(g.title), translate(g.summary)
        s = _score(words, title) * 2 + _score(words, body)
        if s:
            hits.append(Hit("guide", f"{g.emoji} {title}", body, f"/guides/{g.slug}", s + 1))
    for t in tips:
        body = translate(t.text)
        s = _score(words, body)
        if s:
            hits.append(Hit("tip", "💡 " + body[:80] + ("…" if len(body) > 80 else ""), body, t.link or "/", s))
    hits.sort(key=lambda h: -h.score)
    return hits[:30]
