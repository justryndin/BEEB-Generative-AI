BY_KEY = {t.key: t for t in TIPS}


def _pick(pool: list[Tip], seed: str) -> Tip:
    return min(pool, key=lambda t: hashlib.sha1(f"{seed}:{t.key}".encode()).hexdigest())


def tip_of_day(state: set[str], weekday: int, seed: str, step: int = 0) -> Tip:
    """Совет для игрока. state — его ситуация: {"build", "research", "pp_low", "no_push", "holding", "newbie"}.

    step 0 — «совет дня»: сначала срочное для этого игрока (держит баф, нет уведомлений),
    примерно через день — совет на сегодняшний день недели, иначе — любой подходящий к ситуации.
    step > 0 — «ещё совет»: по кругу через всю базу, подходящие к ситуации чаще.
    """
    if step == 0:
        for urgent in ("holding", "no_push"):
            if urgent in state:
                return _pick([t for t in TIPS if urgent in t.when], seed)
        today = [t for t in TIPS if weekday in t.days and (not t.when or set(t.when) & state)]
        # Совет «на сегодня» — примерно через день, иначе по пятницам был бы всегда один и тот же.
        if today and int(hashlib.sha1(f"day:{seed}".encode()).hexdigest(), 16) % 2 == 0:
            return _pick(today, seed)
    fits = [t for t in TIPS if not t.when or set(t.when) & state]
    order = sorted(fits, key=lambda t: hashlib.sha1(f"{seed}:{t.key}".encode()).hexdigest())
    return order[step % len(order)]


def player_tip(svc, player, now: int, tz, step: int = 0) -> Tip:
    """Совет для конкретного игрока: его ситуация + день недели по местному времени."""
    from datetime import datetime

    from .service import KINDS
    from .timeparse import DAY

    state = {k for k in KINDS if svc.active_timer(player["id"], k) is not None}
    level = player["pp_level"]
    if level is None or level < svc.setting_float("priority_below"):
        state.add("pp_low")
    if not svc.push_subs(player["id"]):
        state.add("no_push")
    if player["id"] in svc.holding_map(now):
        state.add("holding")
    if now - (player["agreed_at"] or player["created_at"] or now) < 7 * DAY:
        state.add("newbie")
    today = datetime.fromtimestamp(now, tz)
    return tip_of_day(state, today.weekday(), f"{player['id']}:{today:%Y-%m-%d}", step)
